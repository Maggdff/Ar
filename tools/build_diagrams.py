def validate():
    lessons = {l["id"] for l in json.loads((ASSETS / "lessons.json").read_text(encoding="utf-8"))["lessons"]}
    for d in D:
        assert d["lessonId"] in lessons, f'{d["id"]}: lesson {d["lessonId"]} not in app'
        assert d["kind"] in ("chips", "reveal", "flow", "timeline"), d["id"]
        if d["kind"] == "flow":
            ids = {n["id"] for n in d["nodes"]}
            assert len(ids) == len(d["nodes"]), d["id"] + " duplicate node"
            for n in d["nodes"]:
                if n["answer"]:
                    assert not n["yes"] and not n["no"], (d["id"], n["id"])
                else:
                    assert n["text"] and n["yes"] in ids and n["no"] in ids, (d["id"], n["id"])
        else:
            assert d["items"], d["id"]
            for i in d["items"]:
                assert i["label"] and i["weight"] > 0, d["id"]

if __name__ == "__main__":
    validate()
    (ASSETS / "diagrams.json").write_text(json.dumps(D, ensure_ascii=False, indent=1), encoding="utf-8")
    print("diagrams:", len(D))
