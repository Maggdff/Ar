def build(start=149):
    rng = random.Random(2026)
    out = []
    for i, r in enumerate(RAW):
        qid = f"Q{start + i:04d}"
        kind, lesson, diff, src = r[0], r[1], r[2], r[3]
        lessons = [lesson] if isinstance(lesson, str) else list(lesson)
        base = {"id": qid, "unitIds": sorted({U(l) for l in lessons}), "lessonIds": lessons,
                "difficulty": diff, "sourceType": src, "verification": "مؤكد", "appNote": ""}
        if kind == "tf":
            _, _, _, _, text, truth, expl, corr = r
            base.update(text=text, type="true_false", options=[SAHEEH, KHATA],
                        answer=SAHEEH if truth else KHATA, explanation=expl,
                        correctionIfFalse="" if truth else corr)
        elif kind == "mcq":
            _, _, _, _, text, right, wrongs, expl = r
            opts = [right] + list(wrongs); assert len(set(opts)) == 4, qid
            rng.shuffle(opts)
            base.update(text=text, type="mcq", options=opts, answer=right,
                        explanation=expl, correctionIfFalse="")
        else:
            _, _, _, _, text, answer, expl = r
            base.update(text=text, type=kind, options=[], answer=answer,
                        explanation=expl, correctionIfFalse="")
        out.append(base)
    return out

def apply(questions):
    have = {q["id"] for q in questions}
    for q in build():
        if q["id"] not in have:
            questions.append(q)

