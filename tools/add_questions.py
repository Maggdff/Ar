def tf(lesson, text, truth, expl, *rest):
    """صحيح: tf(l, text, True, expl[, diff[, src]])؛ خطأ: tf(l, text, False, expl, corr[, diff[, src]])"""
    if truth:
        corr, rest = "", list(rest)
    else:
        corr, rest = rest[0], list(rest[1:])
    diff = rest[0] if len(rest) > 0 else "سهل"
    src = rest[1] if len(rest) > 1 else NEW
    RAW.append(("tf", lesson, diff, src, text, truth, expl, corr))

def mcq(lesson, text, right, wrongs, expl, diff="سهل", src=NEW):
    RAW.append(("mcq", lesson, diff, src, text, right, wrongs, expl))

def free(kind, lesson, text, answer, expl, diff="متوسط", src=NEW):
    RAW.append((kind, lesson, diff, src, text, answer, expl))

